// Условие:
// Ты находишься на 0-й ступеньке, и хочешь подняться на n-ю.
// Каждый раз ты можешь подниматься либо на 1, либо на 2 ступеньки.
// Сколько уникальных способов добраться до n?

function climbStairs(n) {
  if (n <= 2) return n;

  let first = 1,
    second = 2;

  for (let i = 3; i <= n; i++) {
    let third = first + second;
    first = second;
    second = third;
  }

  return second;
}

